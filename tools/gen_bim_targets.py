"""Generate a build target for each distinct BIM.AR monster module (docs/BIM_AR.md, step 3).

Reads extracted/bim/manifest.json (written by tools/bim_ar.py --extract) and writes config/bim/<name>.yaml for
every module except bim_base, which has its own hand-written config/bim_base.yaml. The 85 modules (52 W0 tails at
0x800DA86C, 24 W1 at 0x800DBB8C, 9 W2 at 0x800DCEAC) all have the same shape:

  id word, pointer table into the module's own code, data   -> [0x0, .rodata, <name>] (the unit's own rodata:
                                                                part of the table is a jump table into its code)
  code from the lowest pointer target to the module's end    -> [start, cpp, <name>]

They call only the EXE and bim_base, so they link against those two (configure.py, DEPENDS). Rerun this after
bim_ar.py changes; it overwrites config/bim/ and never touches src/.

  python tools/gen_bim_targets.py
"""
import json
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = (ROOT / "config" / "bim_base.yaml").read_text()


def code_start(data, vram):
    """The module's first function: the lowest pointer from its table into itself (its first prologue)."""
    words = [struct.unpack_from("<I", data, o)[0] for o in range(0, len(data) - 3, 4)]
    targets = [w - vram for w in words if vram <= w < vram + len(data) and (w - vram) % 4 == 0]
    start = min(targets)
    first = words[start // 4]
    if first >> 16 != 0x27BD or not first & 0x8000:
        raise ValueError(f"no prologue at {start:#x}")
    return start


def first_jtbl(name, vram):
    """Offset of the module's first jump table, from a previous split's asm (None if it has none)."""
    found = []
    for s in (ROOT / "asm" / "bim" / name).rglob("*.s"):
        found += [int(m, 16) for m in re.findall(r"^(?:dlabel|glabel) jtbl_([0-9A-F]{8})", s.read_text(), re.M)]
    return min(found) - vram if found else None


def main():
    manifest = json.loads((ROOT / "extracted" / "bim" / "manifest.json").read_text())
    out = ROOT / "config" / "bim"
    out.mkdir(exist_ok=True)
    for old in out.glob("*.yaml"):
        old.unlink()
    opts = TEMPLATE[TEMPLATE.index("options:"):TEMPLATE.index("segments:")]
    names = []
    for e in manifest:
        name = e["name"]
        if name == "bim_base":
            continue
        data = (ROOT / "extracted" / "bim" / f"{name}.bin").read_bytes()
        start = code_start(data, e["vram"])
        o = (opts.replace("basename: bim_base", f"basename: {name}")
             .replace("base_path: ..", "base_path: ../..")  # config/bim/ is one level deeper
             .replace("target_path: extracted/bim/bim_base.bin", f"target_path: extracted/bim/{name}.bin")
             .replace("elf_path: build/bim_base.elf", f"elf_path: build/bim/{name}.elf")
             .replace("asm_path: asm/bim_base", f"asm_path: asm/bim/{name}")
             .replace("src_path: src/bim_base", f"src_path: src/bim/{name}")
             .replace("ld_script_path: build/linkers/bim_base.ld", f"ld_script_path: build/linkers/bim/{name}.ld")
             .replace("undefined_funcs_auto.bim_base.txt", f"bim/undefined_funcs_auto.{name}.txt")
             .replace("undefined_syms_auto.bim_base.txt", f"bim/undefined_syms_auto.{name}.txt")
             # the functions it shares with other modules, named once for all of them (tools/bim_shared.py)
             .replace("    - config/symbols/bim_base.txt\n",
                      f"    - config/symbols/bim_base.txt\n    - config/symbols/bim/{name}.txt\n"))
        # GCC aligns a jump table to 8 relative to its unit's rodata, and modules load at 4 mod 8. So where a module
        # has jump tables (all at +0xC, after the 12-byte id/pointer block), its unit's rodata starts at the first.
        jt = first_jtbl(name, e["vram"])
        if jt:
            rodata_rows = (f"      - [0x0, rodata] # id word and the entry pointer\n"
                           f"      - [{jt:#X}, .rodata, {name}] # from the first jump table (aligned to 8): tables, data\n")
        else:
            rodata_rows = f"      - [0x0, .rodata, {name}] # id word, pointer table, data\n"
        uses = f"{e['blocks']} block{'s' if e['blocks'] != 1 else ''}"
        ids = f", SECT.DAT ids {e['sect_ids']}" if e.get("sect_ids") else ""
        text = (f"name: BIM.AR module {name}\n"
                f"# Generated by tools/gen_bim_targets.py from extracted/bim/manifest.json: do not edit.\n"
                f"# A monster overlay module ({uses}{ids}); see docs/BIM_AR.md.\n"
                f"sha1: {e['sha1']}\n" + o +
                f"segments:\n  - name: {name}\n    type: code\n    start: 0x0\n    vram: {e['vram']:#X}\n"
                f"    subsegments:\n" + rodata_rows +
                f"      - [{start:#X}, cpp, {name}]\n\n  - [{len(data):#X}]\n").replace("0X", "0x")
        (out / f"{name}.yaml").write_text(text)
        names.append(name)
    print(f"wrote {len(names)} targets to config/bim/")


if __name__ == "__main__":
    main()
