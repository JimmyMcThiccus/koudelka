"""Generate config/pins.txt from a byte-identical build.

A pin is an overlay symbol that another image reaches by absolute address:
the EXE calling into the shared overlay slot, or EFFECT calling into BATTLE.
Run once against a matching build; functional_check.py enforces the result.

Usage: python gen_pins.py <nm.exe>
"""
import re
import subprocess
import sys

OVERLAYS = ["field", "battle", "movie", "capture", "gameend", "effect"]


def by_addr(nm, elf):
    res = subprocess.run([nm, elf], capture_output=True, text=True, check=True)
    out = {}
    for line in res.stdout.splitlines():
        parts = line.split()
        # nm sign-extends to 64 bits
        if len(parts) == 3 and parts[1] in "TtDdRrBb" and not parts[2].endswith(("_START", "_END", "_SIZE", "_VRAM")):
            out.setdefault(int(parts[0], 16) & 0xFFFFFFFF, parts[2])
    return out


def refs(path):
    for line in open(path):
        m = re.match(r"\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+)", line)
        if m:
            yield m.group(1), int(m.group(2), 16)


def main():
    nm = sys.argv[1]
    tables = {o: by_addr(nm, f"build/{o}.elf") for o in OVERLAYS}
    pins = set()
    unresolved = []
    users = [("main", OVERLAYS), ("effect", ["battle"])]
    for user, owners in users:
        for kind in ("funcs", "syms"):
            for name, addr in refs(f"build/linkers/undefined_{kind}_auto.{user}.txt"):
                hit = [(o, tables[o][addr]) for o in owners if o != user and addr in tables[o]]
                if hit:
                    pins.update((o, s, addr, user) for o, s in hit)
                elif addr >= 0x800B6DF0:
                    unresolved.append((user, name, addr))
    with open("config/pins.txt", "w") as f:
        f.write("# Overlay symbols reached by absolute address from another image.\n"
                "# They must stay put in a functional build. Generated by tools/gen_pins.py.\n"
                "# overlay symbol address  # referenced from\n")
        for o, s, a, u in sorted(pins, key=lambda p: (p[0], p[2])):
            f.write(f"{o} {s} {a:#010x}  # {u}\n")
        for u, n, a in unresolved:
            f.write(f"# not pinned: {u} references {n} at {a:#010x}; no overlay symbol starts there "
                    f"(code/data from another module, or past an overlay's end); stays absolute\n")
    print(f"{len(pins)} pins, {len(unresolved)} unresolved references")


if __name__ == "__main__":
    main()
