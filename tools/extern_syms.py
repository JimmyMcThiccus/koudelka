"""Write an overlay's external-symbol linker script for a shiftable build.

splat's undefined_*_auto files pin every external symbol to its retail
address. For symbols that a dependency image defines in one of its own
sections (the EXE, or BATTLE for EFFECT), this writes that image's current
linked address instead, so the overlay follows the code when it moves.
Everything else (hardware registers, code from other modules) keeps its
retail address.

Usage: python extern_syms.py <nm.exe> <out.ld> <undefined.txt>... --defined <dep.elf>...
"""
import re
import subprocess
import sys

# nm types for symbols defined inside a section (not absolute 'A' assignments)
SECTION_TYPES = set("TtDdRrBbSsGgVv")


def main():
    args = sys.argv[1:]
    nm, out = args[0], args[1]
    split = args.index("--defined")
    undef_files, deps = args[2:split], args[split + 1:]
    defined = {}
    for elf in deps:
        res = subprocess.run([nm, elf], capture_output=True, text=True, check=True)
        for line in res.stdout.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] in SECTION_TYPES:
                defined.setdefault(parts[2], int(parts[0], 16) & 0xFFFFFFFF)  # nm sign-extends
    linked = pinned = 0
    with open(out, "w") as o:
        o.write("/* generated by tools/extern_syms.py */\n")
        for path in undef_files:
            for line in open(path):
                m = re.match(r"\s*(\w+)\s*=", line)
                if m and m.group(1) in defined:
                    o.write(f"{m.group(1)} = {defined[m.group(1)]:#010X};\n")
                    linked += 1
                else:
                    o.write(line)
                    pinned += bool(m)
    print(f"{out}: {linked} symbols from dependencies, {pinned} at retail addresses")


if __name__ == "__main__":
    main()
