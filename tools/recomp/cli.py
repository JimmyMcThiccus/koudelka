"""Static recompiler: MIPS asm functions -> C for a 32-bit host.

  python -m tools.recomp                       all functions still in asm (INCLUDE_ASM in src/)
  python -m tools.recomp --target battle       one target
  python -m tools.recomp --compile             also compile every output file with clang (i686)
  python -m tools.recomp --matchings --funcs battle:func_800B8474 --prefix recomp_ --out DIR
                                               recompile decompiled functions from asm/*/matchings (tests)

Output (git-ignored, derived from the game's code): build/recomp/<target>/<func>.c, recomp_<target>.h,
and build/recomp/report.{md,json}.
"""
import argparse
import json
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from .analyze import Program, ROOT, TARGETS
from .emit import Emitter, Protos, emit_stub
from . import hostcc

RUNTIME = Path(__file__).resolve().parent / "runtime"


def translate(prog, protos, fi, prefix="", rodata_static=False):
    if fi.problems:
        return emit_stub(fi, protos, prefix), False
    try:
        return Emitter(prog, protos, fi, prefix, rodata_static).emit(), True
    except ValueError as e:
        fi.problems.append(f"emitter: {e}")
        return emit_stub(fi, protos, prefix), False


def header_for(prog, protos, target, names, prefix=""):
    out = [f"/* Prototypes of the recompiled {target} functions (generated by tools/recomp). */",
           f"#ifndef RECOMP_{target.upper()}_H", f"#define RECOMP_{target.upper()}_H", '#include "recomp.h"', ""]
    for n in sorted(names):
        out.append(f"RECOMP_EXTERN_C {protos.decl(target, n, prefix + n)};")
    out += ["", "#endif", ""]
    return "\n".join(out)


def compile_all(files, out_dir, jobs=8):
    def one(c):
        o = c.with_suffix(".obj")
        cmd = hostcc.compile_cmd(c, o, includes=[RUNTIME], extra=["-w"])
        r = subprocess.run(cmd, capture_output=True, text=True)
        return c, r.returncode, r.stderr
    fails = []
    with ThreadPoolExecutor(jobs) as ex:
        for c, rc, err in ex.map(one, files):
            if rc:
                fails.append((c, err))
    return fails


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--target", action="append", choices=TARGETS)
    ap.add_argument("--out", default=str(ROOT / "build" / "recomp"))
    ap.add_argument("--funcs", help="comma-separated target:name list (default: all INCLUDE_ASM functions)")
    ap.add_argument("--matchings", action="store_true", help="--funcs may name decompiled functions")
    ap.add_argument("--prefix", default="", help="prefix for the definitions (tests link both versions)")
    ap.add_argument("--static-rodata", action="store_true", help="make the function's own rodata static")
    ap.add_argument("--protos", help="JSON prototype overrides: {name: {stack_args, ret: u32|pair, varargs}}")
    ap.add_argument("--compile", action="store_true", help="compile every output with clang -c (i686)")
    ap.add_argument("-j", type=int, default=8)
    a = ap.parse_args(argv)

    prog = Program()
    prog.load()
    prog.analyze_all()
    protos = Protos(prog, json.loads(Path(a.protos).read_text()) if a.protos else None)

    if a.funcs:
        sel = []
        for spec in a.funcs.split(","):
            t, _, n = spec.strip().partition(":")
            sel.append((t, n))
    else:
        targets = a.target or TARGETS
        sel = [(t, n) for t in targets for n in prog.nonmatching[t]]

    out = Path(a.out)
    written = []
    report = {"translated": [], "stubbed": [], "notes": {}}
    by_target = {}
    for t, n in sel:
        fi = prog.funcs[t].get(n)
        if fi is None:
            sys.exit(f"recomp: no function {t}:{n}")
        code, ok = translate(prog, protos, fi, a.prefix, a.static_rodata)
        d = out / t
        d.mkdir(parents=True, exist_ok=True)
        p = d / f"{a.prefix}{n}.c"
        p.write_text(code, encoding="utf-8", newline="\n")
        written.append(p)
        by_target.setdefault(t, []).append(n)
        (report["translated"] if ok else report["stubbed"]).append(
            {"target": t, "name": n, "insns": len(fi.func.items), **({} if ok else {"why": fi.problems})})
        if fi.notes:
            report["notes"][f"{t}:{n}"] = fi.notes
    for t, names in by_target.items():
        (out / t / f"recomp_{t}.h").write_text(header_for(prog, protos, t, names, a.prefix), encoding="utf-8",
                                               newline="\n")
    report["indirect_stack_args"] = prog.indirect_stack_args
    report["ret_pair"] = sorted(f"{t}:{fi.name}" for t in prog.targets for fi in prog.funcs[t].values() if fi.ret_pair)
    if not a.funcs:
        (out / "report.json").write_text(json.dumps(report, indent=1), encoding="utf-8")
        write_report_md(out / "report.md", report)
    print(f"recomp: {len(report['translated'])} translated, {len(report['stubbed'])} stubbed -> {out}")
    for s in report["stubbed"]:
        print(f"  stub {s['target']}:{s['name']}: {'; '.join(s['why'])}")
    if a.compile:
        fails = compile_all(written, out, a.j)
        print(f"recomp: compiled {len(written) - len(fails)}/{len(written)} with {hostcc.TARGET}")
        for c, err in fails[:20]:
            print(f"  FAIL {c}\n{err[:2000]}")
        if fails:
            sys.exit(1)


def write_report_md(path, rep):
    lines = ["# Recompiler report (generated)", "",
             f"- translated: {len(rep['translated'])}",
             f"- stubbed (abort at run time): {len(rep['stubbed'])}", "", "## Stubbed", ""]
    for s in rep["stubbed"]:
        lines.append(f"- `{s['target']}:{s['name']}`: {'; '.join(s['why'])}")
    lines += ["", "## Notes", ""]
    for k, v in rep["notes"].items():
        lines.append(f"- `{k}`: {'; '.join(v)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
