"""Configure the PC port build of the EXE (docs/PORT_PHASE2.md).

    .venv/Scripts/python.exe port/configure_port.py [--no-build] [--cd <disc 1 .bin>]

Runs the generators (tools/port/hostify.py, tools/recomp --target main, tools/port/gen_data.py), copies the
runtime DLLs and ps1_syms.txt next to the exe, writes build-port.ninja and runs ninja on it. Output:
build/port/koudelka.exe (+ .pdb, .map, koudelka-port.log after a run). Rerun after src/ changes.

Needs bin/port/ (tools/port/fetch_deps.py) and a configured PS1 build (configure.py: asm/ and build/*.elf).
"""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
import ninja_syntax  # noqa: E402
from tools.recomp import hostcc  # noqa: E402
from tools.port.hostify import GAME_FLAGS  # noqa: E402

PY = sys.executable
B = ROOT / "build" / "port"
DEPS = ROOT / "bin" / "port"
PSYCROSS = DEPS / "psycross"
SDL2 = DEPS / "sdl2"
OPENAL = DEPS / "openal"
CLANG = str(hostcc.CLANG)
COMMON = " ".join(hostcc.COMMON_FLAGS) + " -g -fno-omit-frame-pointer"
LIBS = [SDL2 / "lib" / "x86" / "SDL2.lib", OPENAL / "libs" / "Win32" / "OpenAL32.lib", "-ldbghelp", "-luser32",
        "-lgdi32", "-lshell32", "-lwinmm", "-lopengl32", "-ladvapi32"]


def rel(p):
    p = Path(p)
    try:
        return p.relative_to(ROOT).as_posix()
    except ValueError:
        return p.as_posix()


def run(cmd):
    print("configure_port: " + " ".join(str(c) for c in cmd[1:3]))
    subprocess.run([str(c) for c in cmd], cwd=ROOT, check=True)


def default_cd():
    main = Path(subprocess.run(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"], cwd=ROOT,
                               capture_output=True, text=True, check=True).stdout.strip()).parent
    return main / "Koudelka_Game_Data" / "Koudelka (USA) (Disc 1).bin"


def ps1_syms():
    """address name, for every symbol of the EXE and the overlays (llvm-nm on the PS1 ELFs)."""
    lines = set()
    nm = hostcc.LLVM_BIN / "llvm-nm.exe"
    for elf in ["slus_010.51", "field", "battle", "movie", "capture", "gameend", "effect"]:
        p = ROOT / "build" / f"{elf}.elf"
        if not p.exists():
            continue
        r = subprocess.run([str(nm), "--defined-only", str(p)], capture_output=True, text=True)
        for l in r.stdout.splitlines():
            parts = l.split()
            if len(parts) == 3 and parts[1] in "TtDdRrBb" and not parts[2].startswith("."):
                pre = "" if elf == "slus_010.51" else elf + ":"
                lines.add(f"{parts[0][-8:]} {pre}{parts[2]}")
    return "\n".join(sorted(lines)) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--cd", help="default disc 1 image baked into the exe")
    a = ap.parse_args()
    for d in (PSYCROSS, SDL2, OPENAL):
        if not d.exists():
            sys.exit(f"configure_port: {rel(d)} is missing: run tools/port/fetch_deps.py")

    # generators
    run([PY, ROOT / "tools" / "port" / "hostify.py"])
    run([PY, "-m", "tools.recomp", "--target", "main", "--static-rodata"])
    run([PY, ROOT / "tools" / "port" / "gen_data.py"])

    B.mkdir(parents=True, exist_ok=True)
    cd = Path(a.cd) if a.cd else default_cd()
    cfg = f'#define PORT_DEFAULT_CD "{cd.as_posix()}"\n'
    if not (B / "port_config.h").exists() or (B / "port_config.h").read_text() != cfg:
        (B / "port_config.h").write_text(cfg)
    shutil.copy2(SDL2 / "lib" / "x86" / "SDL2.dll", B / "SDL2.dll")
    shutil.copy2(OPENAL / "bin" / "Win32" / "soft_oal.dll", B / "OpenAL32.dll")
    (B / "ps1_syms.txt").write_text(ps1_syms())

    game = sorted((B / "hsrc" / "main").glob("*.cpp"))
    # a function port/ defines (the context switch in port/fibers.cpp, ...) replaces its recompiled twin
    overrides = set()
    for p in (ROOT / "port").glob("*.c*"):
        overrides.update(re.findall(r"^[^\s#/][^;\n]*\b(func_[0-9A-F]{8})\s*\([^;\n]*\)\s*$",
                                    p.read_text(encoding="utf-8"), re.M))
    all_recomp = sorted((ROOT / "build" / "recomp" / "main").glob("*.c"))
    recomp = [p for p in all_recomp if p.stem not in overrides]
    replaced = sorted(p.stem for p in all_recomp if p.stem in overrides)
    if replaced:
        print("configure_port: port/ replaces " + ", ".join(replaced))
    pc_src = sorted(p for p in (PSYCROSS / "src").rglob("*") if p.suffix.lower() in (".c", ".cpp"))
    port_src = sorted(p for p in (ROOT / "port").glob("*") if p.suffix in (".c", ".cpp"))

    out = open(ROOT / "build-port.ninja", "w")
    n = ninja_syntax.Writer(out, width=120)
    n.comment("PC port of the EXE, generated by port/configure_port.py. Do not edit.")
    n.variable("builddir", rel(B))
    inc_game = f"-I port/include -I {rel(B / 'hinc')}"
    inc_pc = " ".join(f"-I {rel(x)}" for x in [PSYCROSS / "include", PSYCROSS / "include" / "psx", PSYCROSS / "src",
                                               SDL2 / "include", OPENAL / "include"])
    # VSyncCallback/VSync renamed: port/intr.cpp takes the game's calls and runs its callback on the game thread.
    # USE_EXTENDED_PRIM_POINTERS=0: PsyCross keeps the PS1 packet layout (P_TAG addr:24), the layout the game's
    # own primitives and OT code use. That works unchanged because the exe is linked at a fixed base below
    # 16 MB (link_base), so every game prim and OT entry (game heap in port_ram, main-thread stack) has a
    # 24-bit host address. main.cpp checks it at start-up.
    pc_flags = "-DVSyncCallback=psyx_VSyncCallback -DVSync=psyx_VSync -DUSE_EXTENDED_PRIM_POINTERS=0 -D_WINDOWS -D_DEBUG -D_ITERATOR_DEBUG_LEVEL=0 -D__PRFCHWINTRIN_H -include stdarg.h -Wno-c++11-narrowing -w"
    q = f'"{CLANG}"'
    n.rule("cxx_game", f"{q} {COMMON} -O2 {inc_game} {' '.join(GAME_FLAGS)} -MD -MF $out.d -c $in -o $out",
           depfile="$out.d", deps="gcc", description="game $in")
    n.rule("cc_recomp", f"{q} {COMMON} -O2 -w -Dprintf=game_printf -I tools/recomp/runtime -include port/include/port_recomp.h "
                        f"-MD -MF $out.d -c $in -o $out", depfile="$out.d", deps="gcc", description="recomp $in")
    n.rule("cc_pc", f"{q} {COMMON} -O2 -x c {pc_flags} {inc_pc} -MD -MF $out.d -c $in -o $out",
           depfile="$out.d", deps="gcc", description="psycross $in")
    n.rule("cxx_pc", f"{q} {COMMON} -O2 -x c++ {pc_flags} {inc_pc} -MD -MF $out.d -c $in -o $out",
           depfile="$out.d", deps="gcc", description="psycross $in")
    n.rule("cc_port", f"{q} {COMMON} -O1 -D_CRT_SECURE_NO_WARNINGS -I port -I port/include -I {rel(B)} -MD -MF $out.d -c $in -o $out",
           depfile="$out.d", deps="gcc", description="port $in")
    n.rule("as", f"{q} --target={hostcc.TARGET} -c $in -o $out", description="as $in")
    link_base = f"{q} --target={hostcc.TARGET} -fuse-ld=lld -g -Wl,/base:0x400000 -Wl,/dynamicbase:no " + " ".join(
        f'"{rel(x)}"' if isinstance(x, Path) else x for x in LIBS)
    n.rule("stubs", f'"{PY}" tools/port/gen_stubs.py --rsp {rel(B / "objs.rsp")} --out {rel(B / "stubs")} -- '
                    f"{link_base} -Wl,/safeseh:no", description="stubs (probe link)")
    n.rule("link", f"{link_base} -Wl,/safeseh:no @{rel(B / 'objs.rsp')} {rel(B / 'stubs' / 'stubs.obj')} "
                   f"@{rel(B / 'stubs' / 'link.rsp')} -Wl,/map:$out.map -o $out", description="link $out")

    objs = []
    for s in game:
        o = B / "obj" / "game" / (s.stem + ".obj")
        n.build(rel(o), "cxx_game", rel(s))
        objs.append(o)
    for s in recomp:
        o = B / "obj" / "recomp" / (s.stem + ".obj")
        n.build(rel(o), "cc_recomp", rel(s))
        objs.append(o)
    data_o = B / "obj" / "data" / "main_data.obj"
    n.build(rel(data_o), "as", rel(B / "data" / "main_data.s"))
    objs.append(data_o)
    for s in pc_src:
        o = B / "obj" / "psycross" / (s.name + ".obj")
        n.build(rel(o), "cc_pc" if s.suffix == ".c" else "cxx_pc", rel(s))
        objs.append(o)
    for s in port_src:
        o = B / "obj" / "port" / (s.name + ".obj")
        n.build(rel(o), "cc_port", rel(s))
        objs.append(o)
    (B / "objs.rsp").write_text("".join(f'"{rel(o)}"\n' for o in objs))
    stubs_s, link_rsp = B / "stubs" / "stubs.s", B / "stubs" / "link.rsp"
    n.build([rel(stubs_s), rel(link_rsp), rel(B / "stubs" / "stubs.txt")], "stubs", [rel(o) for o in objs],
            implicit=[rel(B / "aliases.txt"), "tools/port/gen_stubs.py"])
    n.build(rel(B / "stubs" / "stubs.obj"), "as", rel(stubs_s))
    n.build(rel(B / "koudelka.exe"), "link", [rel(o) for o in objs] + [rel(B / "stubs" / "stubs.obj")],
            implicit=[rel(link_rsp)])
    n.default(rel(B / "koudelka.exe"))
    out.close()
    print(f"configure_port: {len(game)} game files, {len(recomp)} recompiled, {len(pc_src)} PsyCross, "
          f"{len(port_src)} port -> build-port.ninja")
    if not a.no_build:
        ninja = Path(PY).parent / "ninja.exe"
        sys.exit(subprocess.run([str(ninja), "-f", "build-port.ninja", "-k", "0"], cwd=ROOT).returncode)


if __name__ == "__main__":
    main()
